// As estuturas condicionais são utilizadas para tomar decisões no código, permitindo que diferentes blocos de código sejam executados com base em condições específicas.

// If/Else - Condicionais
// If - Verifica se a condição é verdadeira e executa o bloco de código correspondente. Caso contrário, executa o bloco de código do else.

let idade = 12;

if (idade >= 18) {
    console.log("Você é maior de idade.");
} else {
    console.log("Você é menor de idade.");
}

// IF, ELSE, IF, ELSE (Multiplas Condições)

let idade2 = 10;

if (idade2 < 18) {
    console.log("Você é uma criança ");
} else if (idade2 < 18) {
    console.log("Você é um adolescente.");
} else {
    console.log("Você é um adulto.");
}